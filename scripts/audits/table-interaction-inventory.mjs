import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const roots = ['src/pages', 'src/components'];
const output = process.argv[2];

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const candidates = roots
  .flatMap(walk)
  .filter((path) => path.endsWith('.tsx'))
  .map((path) => ({ path: relative('.', path), source: readFileSync(path, 'utf8') }))
  .filter(({ source }) => /<Table|VirtualizedTable|DataTableHeader/.test(source));

function category(source) {
  if (/VirtualizedTable|VirtualizedDataSection/.test(source)) return 'Virtualized/high-volume';
  if (/ServerPagination|useServerPagination/.test(source)) return 'Server-paginated';
  if (/Inventory|Journal|Ledger|Payment|Treasury|Accounting/i.test(source)) return 'Sensitive/read-review';
  return 'Client/local or embedded';
}

function mark(source, pattern) {
  return pattern.test(source) ? 'نعم' : '—';
}

const rows = candidates.map(({ path, source }) => [
  `\`${path}\``,
  category(source),
  mark(source, /ColumnFilterHeader|FilterDrawer|FiltersBar/),
  mark(source, /useTableLayout|useTableCustomization|useCustomerLayoutPrefs/),
  mark(source, /ServerPagination|useServerPagination/),
  mark(source, /useIsMobile|Mobile|DataCard|ResponsiveItemsTable/),
].join(' | '));

const document = `# OPA-TBL-001 — Table Surface Inventory\n\n` +
  `Generated by \`scripts/audits/table-interaction-inventory.mjs\`. Static trace only; runtime proof remains mandatory per screen.\n\n` +
  `Total candidate surfaces: **${candidates.length}**.\n\n` +
  `| Surface | Initial class | Filter UI | Layout prefs | Server pagination | Responsive signal |\n` +
  `|---|---|---:|---:|---:|---:|\n` +
  rows.join('\n') + '\n';

if (output) writeFileSync(output, document);
else process.stdout.write(document);